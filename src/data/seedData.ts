export function generateInitialPayments(): Payment[] {
  const payments: Payment[] = [];
  const today = '2026-10-24'; // System date

  for (const contract of INITIAL_CONTRACTS) {
    const dates = generateMonthlyPaymentDates(contract.startDate, contract.endDate, contract.rentDueDay);
    
    dates.forEach((dueDate, index) => {
      const isPast = dueDate < today;
      const isCurrentMonth = dueDate.startsWith('2026-10');
      
      let status: 'paid' | 'pending' | 'overdue' = 'pending';
      let paidDate: string | null = null;
      let paidAmount: number | undefined = undefined;

      if (isPast) {
        // Earlier months are marked paid, except maybe 1 or 2 overdue items to showcase alerts
        if (contract.id === 'cnt-1-15' && isCurrentMonth) {
          // Keep this one pending or overdue for current month
          status = 'overdue';
        } else if (contract.id === 'cnt-3-6' && isCurrentMonth) {
          status = 'overdue';
        } else {
          status = 'paid';
          paidDate = dueDate;
          paidAmount = contract.monthlyRent;
        }
      } else {
        status = 'pending';
      }

      payments.push({
        id: `pay-${contract.id}-${index + 1}`,
        contractId: contract.id,
        unitId: contract.unitId,
        dueDate,
        amount: contract.monthlyRent,
        paidAmount,
        paidDate,
        status,
        note: status === 'paid' ? 'تم السداد نقداً بإيصال' : undefined,
      });
    });
  }

  return payments;
}
